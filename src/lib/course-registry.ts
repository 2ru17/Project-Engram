export const COURSE_MAP: Map<string, CourseInfo> = new Map(
  COURSE_REGISTRY.map((c) => [c.code.toUpperCase(), c])
);

export function getCourseInfo(code: string): CourseInfo | undefined {
  if (!code) return undefined;
  return COURSE_MAP.get(code.toUpperCase());
}

export function getDomainInfo(category?: string): StarDomainInfo {
  if (category && category in STAR_DOMAINS) {
    return STAR_DOMAINS[category as StarDomainId];
  }
  return STAR_DOMAINS.systems;
}
